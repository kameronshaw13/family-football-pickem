"""Build a verified NCAA SVG lookup without changing saved ESPN team identities."""
import concurrent.futures, json, pathlib, re, time, unicodedata, urllib.request, xml.etree.ElementTree as ET
ROOT = pathlib.Path(__file__).resolve().parents[1]
ALIASES = {
 '2026':'appalachian-st','2029':'ark-pine-bluff','2934':'bakersfield','2110':'central-ark','2115':'central-conn-st','2117':'central-mich','232':'col-of-charleston','2127':'charleston-so','324':'coastal-caro','2174':'detroit','2193':'east-tenn-st','2837':'east-tex-am','2197':'eastern-ill','2198':'eastern-ky','2199':'eastern-mich','331':'eastern-wash','161':'fdu','526':'fgcu','2229':'fiu','85':'iu-indy','2443':'new-orleans','309':'la-lafayette','2379':'umes','2377':'mcneese-st','2390':'miami-fl','2393':'middle-tenn','2400':'mississippi-val','116':'mt-st-marys','152':'north-carolina-st','2447':'nicholls-st','2453':'north-ala','2464':'northern-ariz','2458':'northern-colo','2459':'northern-ill','94':'northern-ky','219':'penn','2504':'prairie-view','2870':'ipfw','2511':'queens-nc','2545':'southeastern-la','2608':'st-marys-ca','2534':'sam-houston-st','2547':'seattle','6':'south-ala','58':'south-fla','2546':'southeast-mo-st','79':'southern-ill','88':'southern-ind','2582':'southern-u','2599':'st-johns-ny','2900':'st-thomas-mn','399':'albany-ny','82':'ill-chicago','2433':'la-monroe','30':'southern-california','250':'texas-arlington','292':'utrgv','2698':'west-ga','2717':'western-caro','2710':'western-ill','98':'western-ky','2711':'western-mich'
}
ASSET_SLUG_ALIASES = {"east-tex-am": "tex-am-commerce"}

def fetch(url):
 with urllib.request.urlopen(url, timeout=20) as response: return response.read()
def normalize(value):
 value=unicodedata.normalize('NFKD', str(value)).encode('ascii','ignore').decode().lower().replace('&','and')
 return re.sub('[^a-z0-9]','',re.sub(r'\bstate\b','st',value))
def main():
 schools=json.loads(fetch('https://ncaa-api.henrygd.me/schools-index'))
 school_slugs={s['slug'] for s in schools}
 index={}
 for school in schools:
  for field in ('slug','name','long'):
   if school.get(field): index.setdefault(normalize(school[field]),set()).add(school['slug'])
 teams={}; cbb_ids=set(); team_guids={}
 for sport,path in [('CBB','basketball/mens-college-basketball'),('CFB','football/college-football')]:
  data=json.loads(fetch(f'https://site.api.espn.com/apis/site/v2/sports/{path}/teams?limit=1000'))
  for row in data['sports'][0]['leagues'][0]['teams']:
   team=row['team']; team_id=str(team['id']); teams[team_id]=team
   for logo in team.get('logos',[]):
    match=re.search(r'/guid/([^/]+)/',logo.get('href',''))
    if match:team_guids.setdefault(team_id,set()).add(match[1])
   if sport=='CBB':cbb_ids.add(str(team['id']))
 candidates={}
 for team_id,team in teams.items():
  matches=index.get(normalize(team.get('location','')),set())
  slug=ALIASES.get(team_id) or (next(iter(matches)) if len(matches)==1 else None)
  if slug and slug in school_slugs:candidates[team_id]=ASSET_SLUG_ALIASES.get(slug,slug)
 def verify(slug):
  url=f'https://www.ncaa.com/sites/default/files/images/logos/schools/bgl/{slug}.svg'
  for attempt in range(2):
   try:
    raw=fetch(url); root=ET.fromstring(raw)
    if root.tag.split('}')[-1]!='svg':return slug,False
    if any(element.tag.split('}')[-1].lower() in ('script','foreignobject') for element in root.iter()):return slug,False
    return slug,True
   except Exception:
    if attempt==0:time.sleep(.25)
  return slug,False
 valid={}
 with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
  for i,(slug,ok) in enumerate(pool.map(verify,sorted(set(candidates.values()))),1):
   valid[slug]=ok
   if i%100==0: print(f'Verified {i} schools',flush=True)
 ids={team_id:slug for team_id,slug in candidates.items() if valid[slug]}
 guids={}
 for team_id,slug in ids.items():
  for guid in team_guids.get(team_id,set()):guids[guid]=slug
 text='// Generated by scripts/sync-ncaa-logos.py; verified against NCAA SVG assets.\n'
 text+='export const NCAA_SVG_BY_ESPN_ID: Readonly<Record<string, string>> = '+json.dumps(dict(sorted(ids.items())),indent=2)+';\n'
 text+='export const NCAA_SVG_BY_ESPN_GUID: Readonly<Record<string, string>> = '+json.dumps(dict(sorted(guids.items())),indent=2)+';\n'
 (ROOT/'lib/ncaaLogos.ts').write_text(text)
 report={'verifiedSchools':len(set(ids.values())),'mappedEspnTeams':len(ids),'cbbTeams':len(cbb_ids),'cbbSvgTeams':len(cbb_ids & ids.keys()),'cbbFallbacks':[(i,teams[i]['displayName'],candidates.get(i)) for i in sorted(cbb_ids-ids.keys())], 'unavailableSvgs':[slug for slug,ok in valid.items() if not ok]}
 print(json.dumps(report,indent=2),flush=True)
if __name__=='__main__':main()
